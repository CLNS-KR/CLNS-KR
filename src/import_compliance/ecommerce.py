def tag_for_rule(rule_id: str) -> str:
    return TAG_BY_RULE.get(str(rule_id), "PRICE_AD_CLAIM")


def regulation_tags(result: Dict[str, Any]) -> List[str]:
    tags: List[str] = []
    for finding in result.get("findings") or []:
        tag = tag_for_rule(str(finding.get("rule_id") or ""))
        if tag not in tags:
            tags.append(tag)
    if (result.get("disclosure_check") or {}).get("missing"):
        if "SELLER_DISCLOSURE" not in tags:
            tags.append("SELLER_DISCLOSURE")
    return tags
