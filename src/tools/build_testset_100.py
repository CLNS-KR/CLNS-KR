def build() -> dict:
    cases = []
    for index, row in enumerate(ROWS, start=1):
        domain, product, query, facts, verdict, tags, primary, severity, note = row
        cases.append({
            "case_id": f"CASE-{index:03d}",
            "domain": domain,
            "domain_ko": DOMAINS[domain],
            "product_ko": product,
            "query": query,
            "facts": facts,
            "expected_verdict": verdict,
            "required_findings": list(tags),
            "primary_case_id": primary,
            "severity": severity,
            "note_ko": note,
        })
    return {
        "testset_version": "1.0.0",
        "schema_version": "0.1.3",
        "jurisdiction": "KR",
        "created_on": "2026-11-18",
        "case_count": len(cases),
        "domains": DOMAINS,
        "note_ko": (
            "대표 100개 품목 테스트셋. 각 케이스는 분야(domain)·기대 판정(expected_verdict)·"
            "필수 규제 태그(required_findings)를 가지며, 필수 태그가 응답에서 빠지면 중대 규제 "
            "누락(FN)으로 센다. required_findings 는 standards.CASE_REGULATION_TAGS 의 태그 "
            "어휘를 쓴다. 의료기기·위생용품 분야는 세관장확인·목록통관 축에서만 검증하며 "
            "(전용 규제 카드 없음) 이 한계는 응답의 scope_limits_ko 에도 표시된다."
        ),
        "cases": cases,
    }


def check(payload: dict) -> list:
    problems = []
    cases = payload["cases"]
    if len(cases) != 100:
        problems.append(f"case_count={len(cases)} (expected 100)")
    ids = [case["case_id"] for case in cases]
    if len(ids) != len(set(ids)):
        problems.append("duplicate case_id")
    allowed = {"check_likely", "info_needed", "low_risk"}
    per_domain = {}
    for case in cases:
        per_domain[case["domain"]] = per_domain.get(case["domain"], 0) + 1
        if case["domain"] not in DOMAINS:
            problems.append(f"{case['case_id']}: unknown domain {case['domain']}")
        if case["expected_verdict"] not in allowed:
            problems.append(f"{case['case_id']}: bad expected_verdict")
        if not case["required_findings"]:
            problems.append(f"{case['case_id']}: empty required_findings")
        if not case["query"].strip():
            problems.append(f"{case['case_id']}: empty query")
        if not isinstance(case["facts"], dict):
            problems.append(f"{case['case_id']}: facts must be object")
    for domain in DOMAINS:
        if domain not in per_domain:
            problems.append(f"domain {domain} has no cases")
    return problems


def main(argv: list) -> int:
    payload = build()
    problems = check(payload)
    if "--check" not in argv:
        with open(OUT_PATH, "w", encoding="utf-8") as handle:
            json.dump(payload, handle, ensure_ascii=False, indent=1)
            handle.write("\n")
        print(f"wrote {OUT_PATH} cases={payload['case_count']}")
    if problems:
        for problem in problems:
            print("PROBLEM:", problem)
        return 1
    print("OK testset structure")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
